import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const root = new URL("../out/", import.meta.url);
const episodes = JSON.parse(await readFile(new URL("../content/episodes.json", import.meta.url), "utf8"));
const home = await readFile(new URL("index.html", root), "utf8");
assert.ok(home.includes("Good questions."));
assert.ok(home.includes("/_next/static/"), "The export must be generated by Next.js");
assert.ok(!home.includes("Loading the conversations"), "Episodes must render in the initial HTML");
const socials = await readFile(new URL("socials/index.html", root), "utf8");
const socialLinks = [
  "https://www.youtube.com/@MAHESHNANDIGAM-t9z",
  "https://www.youtube.com/@MaheshNandigamShorts",
  "https://www.youtube.com/@MaheshNandigamClips",
  "https://x.com/mahesh_labs",
  "https://x.com/maheshstwt",
  "https://x.com/maheshn_dev",
  "https://www.linkedin.com/company/mahesh-labs/",
  "https://www.linkedin.com/in/mahesh1822/",
  "https://www.linkedin.com/in/mahesh-nandigam/",
  "https://www.instagram.com/mahesh.labs/",
  "https://www.instagram.com/maheshnandigam_/",
];
const socialsMain = socials.match(/<main\b[^>]*>([\s\S]*?)<\/main>/)?.[1];
assert.ok(socialsMain, "The social directory must be prerendered");
for (const url of socialLinks) assert.ok(socialsMain.includes(`href="${url}"`), `Missing social destination: ${url}`);
for (const html of [home, socials]) {
  const header = html.match(/<header\b[^>]*>([\s\S]*?)<\/header>/)?.[1];
  assert.ok(header?.includes('href="/socials/"'), "The header must link to the social directory");
  assert.ok(header?.includes('href="https://www.youtube.com/@MAHESHNANDIGAM-t9z?sub_confirmation=1"'), "Subscribe must open the main YouTube channel");
  assert.ok(header?.includes('>Subscribe</a>'), "Subscribe must have a visible text label");
  assert.ok(!header?.includes("header-social-link"), "The old social icon group must be removed");
}
for (const episode of episodes) {
  if(episode.guest)assert.ok(home.includes(episode.guest));
  assert.ok(home.includes(episode.externalPlayback ? `watch?v=${episode.videoId}` : `/episodes/${episode.number}/`));
  const html = await readFile(new URL(`episodes/${episode.number}/index.html`, root), "utf8");
  if(episode.guest)assert.ok(html.includes(episode.guest));
  if(episode.chapters.length)assert.ok(html.includes(episode.chapters[episode.chapters.length - 1].time), "Every chapter must be prerendered");
  if (episode.videoId) assert.ok(html.includes(`watch?v=${episode.videoId}`));
  else assert.ok(html.includes(episode.teaser ? "Watch the teaser" : "Coming soon to MaheshLabs"));
}
await readFile(new URL("404.html", root));
console.log(`Verified Next.js export: homepage, social directory and all ${socialLinks.length} destinations, subscription navigation, all ${episodes.length} episode routes, chapter content, YouTube links, and 404 page.`);
