import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const root = new URL("../out/", import.meta.url);
const episodes = JSON.parse(await readFile(new URL("../content/episodes.json", import.meta.url), "utf8"));
const home = await readFile(new URL("index.html", root), "utf8");
assert.ok(home.includes("Good questions."));
assert.ok(home.includes("/_next/static/"), "The export must be generated by Next.js");
assert.ok(!home.includes("Loading the conversations"), "Episodes must render in the initial HTML");
for (const episode of episodes) {
  if(episode.guest)assert.ok(home.includes(episode.guest));
  assert.ok(home.includes(`/episodes/${episode.number}/`));
  const html = await readFile(new URL(`episodes/${episode.number}/index.html`, root), "utf8");
  if(episode.guest)assert.ok(html.includes(episode.guest));
  if(episode.chapters.length)assert.ok(html.includes(episode.chapters[episode.chapters.length - 1].time), "Every chapter must be prerendered");
  if (episode.videoId) assert.ok(html.includes(`watch?v=${episode.videoId}`));
  else assert.ok(html.includes(episode.teaser ? "Watch the teaser" : "Coming soon to MaheshLabs"));
}
await readFile(new URL("404.html", root));
console.log(`Verified Next.js export: homepage, all ${episodes.length} episode routes, chapter content, YouTube links, and 404 page.`);
